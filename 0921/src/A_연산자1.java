
public class A_연산자1{
    public static void main(String[] args) {
        // 비트연산자 :: &, |, ^, >>, <<
        //  !! 위 기호를 보게 된다면? 2진법 변환 !! 
        System.out.println(10 & 6);
        System.out.println(10 | 6);
        System.out.println(10 ^ 6);
        System.out.println(10 >> 1);
        System.out.println(10 << 1);
    }
}