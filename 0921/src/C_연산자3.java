
public class C_연산자3 {
    public static void main(String[] args) {
        // 1항연산자... 2항연산자... 3항연산자(?)

        // [조건식] ? [참일때의 값]:[거짓일때의 값]
        boolean r1 = 5>10 ? true:false;
        System.out.println(r1);

        String r2 = 6>10 ? "참입니다":"거짓입니다";
        System.out.println(r2);
    }   
}
