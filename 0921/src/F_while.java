


public class F_while {
    public static void main(String[] args) {
        // 반복문 :: 조건 만족할 때 "반복"할 명령문 작성
        // while(조건식){
        //     조건 만족할때, 반복할 명령문
        // }

        // !! 언젠가는 반복문 종료하게끔, 조건식 설정하자. !!

        int i = 0;
        while(i<3){
            System.out.println(i);
            i++;
        }   // i=3 되면, 탈출
    }
}
